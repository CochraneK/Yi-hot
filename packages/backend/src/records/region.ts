/** 被公告类型标签污染的 region（应置空，不参与省/市匹配）。 */
const GARBAGE = /公告|申辩|复核|送达决定|列入决定|移出公告/;

export interface NormalizedRegion {
  province: string | null;
  city: string | null;
}

export function normalizeRegion(region: string | null): NormalizedRegion {
  const r = (region ?? "").trim();
  if (!r) return { province: null, city: null };
  if (GARBAGE.test(r)) return { province: null, city: null };

  // 1) 显式省/自治区/直辖市名（全称优先，再试简称）。
  for (const p of PROVINCES) {
    if (r.includes(p.full) || r.includes(p.short)) return { province: p.short, city: null };
  }
  // 2) 地级市 / 地区 / 自治州 / 县 → 省。
  for (const [city, prov] of Object.entries(CITY_TO_PROVINCE)) {
    if (r.includes(city)) return { province: prov, city };
  }
  return { province: null, city: null };
}
